#!/usr/bin/env node
// Single source for launcher icons. Emits:
//   design/app-icons/<id>.svg                                      (review / design handoff)
//   <iosAssets>/<IconSet>.appiconset/                              (1024 PNG + Contents.json)
//   <iosAssets>/AppIconPreview-<Title>.imageset/                   (256 PNG, for in-app pickers)
//   <androidRes>/drawable/<foreground>.xml                         (VectorDrawable)
//   <androidRes>/mipmap-anydpi/<adaptive>.xml                      (adaptive icon)
//
// iOS PNGs are rasterized with ImageMagick (`magick`) and stripped of alpha; app icons must be opaque.
// Android is a 108dp layer with a ~66dp circular safe zone.
//
// Run: node design/app-icons.mjs

import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// ============================================================================
// CONFIG: the only part that changes per app.
// ============================================================================

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const APP = {
  iosAssets: "ios/AppName/Resources/Assets.xcassets",
  androidRes: "android/app/src/main/res",
};

// The mark. Keep it constructible from a formula so variants survive resizing.
// Default idea here: two overlapping circles ("the two of you"). Swap the geometry
// helpers below for a different mark; keep the variant/driver structure.
const SIZE = 1024;      // iOS canvas
const R = 225;          // iOS circle radius
const DX = 129;         // iOS offset from centre
const AV = 108;         // Android layer size (do not change)
const AV_CY = AV / 2;
const AV_R = 20;        // Android circle radius (~66dp safe zone => keep R*2 <= 66-ish visually)
const AV_DX = 11;       // Android offset from centre

// `a` is the circle drawn first (behind), `b` second. `o` is fill-opacity.
//   default  -> the shipped icon
//   deep     -> solid brand ground, light mark (more presence on light home screens)
//   night    -> near-black ground, accent mark (dark/OLED)
//   mono     -> single-ink mark (conservative / print-adjacent)
const variants = [
  { id: "default", title: "Blush", iconSet: "AppIcon", bg: "#FAF6F3",
    a: { c: "#F47F91", o: 1 }, b: { c: "#C83F58", o: 0.85 },
    adaptive: "ic_launcher", foreground: "ic_launcher_foreground", background: "app_window_background",
    android: { a: "@color/app_accent", b: "@color/app_accent_deep" } },

  { id: "deep", title: "Deep", iconSet: "AppIcon-Deep", bg: "#C83F58",
    a: { c: "#FAF6F3", o: 1 }, b: { c: "#FAF6F3", o: 0.7 },
    adaptive: "ic_launcher_deep", foreground: "ic_launcher_foreground_deep", background: "app_accent_deep",
    android: { a: "@color/app_porcelain", b: "@color/app_porcelain" } },

  { id: "night", title: "Night", iconSet: "AppIcon-Night", bg: "#171211",
    a: { c: "#F47F91", o: 1 }, b: { c: "#F47F91", o: 0.6 },
    adaptive: "ic_launcher_night", foreground: "ic_launcher_foreground_night", background: "app_ink",
    android: { a: "@color/app_accent", b: "@color/app_accent" } },

  { id: "mono", title: "Mono", iconSet: "AppIcon-Mono", bg: "#FAF6F3",
    a: { c: "#C83F58", o: 1 }, b: { c: "#C83F58", o: 0.6 },
    adaptive: "ic_launcher_mono", foreground: "ic_launcher_foreground_mono", background: "app_porcelain",
    android: { a: "@color/app_accent_deep", b: "@color/app_accent_deep" } },
];

// ============================================================================
// Generators: usually no change needed.
// ============================================================================

const svgFor = (v) => `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">
  <rect width="${SIZE}" height="${SIZE}" fill="${v.bg}" />
  <circle cx="${SIZE / 2 - DX}" cy="${SIZE / 2}" r="${R}" fill="${v.a.c}" fill-opacity="${v.a.o}" />
  <circle cx="${SIZE / 2 + DX}" cy="${SIZE / 2}" r="${R}" fill="${v.b.c}" fill-opacity="${v.b.o}" />
</svg>
`;

// A circle as a VectorDrawable path (two arcs). Same formula, Android units.
const avCircle = (cx) =>
  `M${cx},${AV_CY}m-${AV_R},0a${AV_R},${AV_R} 0,1 1,${2 * AV_R},0a${AV_R},${AV_R} 0,1 1,${-2 * AV_R},0`;

// Colours come from @color/* resources, never inline hex, so theme and icon move together.
const vectorFor = (v) => `<?xml version="1.0" encoding="utf-8"?>
<!-- ${v.id === "default" ? "Primary launcher mark." : "Alternative launcher mark."} Generated by design/app-icons.mjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${AV}dp"
    android:height="${AV}dp"
    android:viewportWidth="${AV}"
    android:viewportHeight="${AV}">
    <path
        android:fillColor="${v.android.a}"
        android:pathData="${avCircle(AV_CY - AV_DX)}" />
    <path
        android:fillColor="${v.android.b}"
        android:fillAlpha="${v.b.o}"
        android:pathData="${avCircle(AV_CY + AV_DX)}" />
</vector>
`;

// The <monochrome> layer must be a real drawable or Android 13+ themed icons silently break.
const adaptiveFor = (v) => `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/${v.background}" />
    <foreground android:drawable="@drawable/${v.foreground}" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground_mono" />
</adaptive-icon>
`;

const contentsJson = (filename) =>
  JSON.stringify(
    { images: [{ filename, idiom: "universal", platform: "ios", size: "1024x1024" }], info: { author: "xcode", version: 1 } },
    null,
    2,
  ) + "\n";

const write = (path, contents) => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents);
};

const assets = join(root, APP.iosAssets);
const res = join(root, APP.androidRes);

for (const v of variants) {
  const svgPath = join(root, "design/app-icons", `${v.id}.svg`);
  write(svgPath, svgFor(v));

  // iOS: opaque, full-bleed 1024. The OS draws the corners; we never do.
  const pngName = `${v.iconSet}-1024.png`;
  const setDir = join(assets, `${v.iconSet}.appiconset`);
  mkdirSync(setDir, { recursive: true });
  execFileSync("magick", ["-background", "none", svgPath, "-alpha", "off", join(setDir, pngName)], { stdio: "inherit" });
  write(join(setDir, "Contents.json"), contentsJson(pngName));

  // In-app picker thumbnail. App-icon renditions can't be loaded with UIImage(named:),
  // so the appearance grid needs ordinary single-scale imagesets instead.
  const previewName = `AppIconPreview-${v.title}`;
  const previewFile = `${previewName}.png`;
  const previewDir = join(assets, `${previewName}.imageset`);
  mkdirSync(previewDir, { recursive: true });
  execFileSync(
    "magick",
    ["-background", "none", svgPath, "-resize", "256x256", "-alpha", "off", join(previewDir, previewFile)],
    { stdio: "inherit" },
  );
  write(
    join(previewDir, "Contents.json"),
    JSON.stringify({ images: [{ filename: previewFile, idiom: "universal" }], info: { author: "xcode", version: 1 } }, null, 2) + "\n",
  );

  // Android: 108dp layer + 108dp foreground VectorDrawable + adaptive wrapper.
  write(join(res, `drawable/${v.foreground}.xml`), vectorFor(v));
  write(join(res, `mipmap-anydpi/${v.adaptive}.xml`), adaptiveFor(v));
}

console.log(`Generated ${variants.length} launcher icons.`);
console.log("Reminder: add @color entries for app_accent / app_accent_deep / app_ink / app_porcelain.");
